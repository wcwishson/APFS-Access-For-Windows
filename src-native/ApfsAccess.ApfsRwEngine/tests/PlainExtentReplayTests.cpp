int main(int argc, char** argv) {
    try {
        Check(argc == 2, "explicit owned fixture action required");
        const std::string action = argv[1];
        if (action == "produce") Produce(false);
        else if (action == "produce-pending") Produce(true);
        else if (action == "prove") Prove(false);
        else if (action == "corrupt-proof") Prove(true);
        else if (action == "replay-direct") ReplayPending(false);
        else if (action == "replay-coordinator") ReplayPending(true);
        else if (action == "live-pending") LiveCoordinator(false, false);
        else if (action == "live-worker") LiveCoordinator(true, false);
        else if (action == "legacy-capacity") LiveCoordinator(false, true);
        else if (action == "recover-live") ReplayPending(true, true);
        else Check(false, "unknown action");
        std::cout << "PASS PlainExtentReplayTests checks=" << checks << '\n'; return 0;
    } catch (const std::exception& error) { std::cerr << "FAIL PlainExtentReplayTests: " << error.what() << '\n'; return 1; }
}
