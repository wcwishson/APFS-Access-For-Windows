constexpr std::uint64_t Offset = 4096 + 17;
const Bytes Patch(29, std::byte{0x99});
BuilderStore ReplaySpec(bool tight = false) {
    auto spec = CloneSpec(1); std::string error;
    for (auto& record : spec.volumes.front().filesystem_records) if (Type(record) == 3) {
        AppleInodeRecord inode; Check(ApfsExtendedRecordCodec::DecodeInode(record, inode, error), error);
        for (auto& field : inode.extended_fields) field.flags = 0;
        Check(EncodeAppleInodeRecord(inode, record, error), error);
    }
    if (tight) {
        constexpr std::uint64_t blocks = 352;
        auto& volume = spec.volumes.front();
        volume.additional_file_system_allocated_blocks = blocks;
        for (auto& record : volume.filesystem_records) {
            if (Type(record) == 3 && Id(record) == 17) {
                AppleInodeRecord inode; Check(ApfsExtendedRecordCodec::DecodeInode(record, inode, error), error);
                inode.uncompressed_size = blocks * kBlockSize;
                PutU64LE(inode.extended_fields.front().data, 0, inode.uncompressed_size);
                PutU64LE(inode.extended_fields.front().data, 8, inode.uncompressed_size);
                Check(EncodeAppleInodeRecord(inode, record, error), error);
            }
            if (Type(record) == 8) PutU64LE(record.value, 0, blocks * kBlockSize);
        }
        PutU64LE(volume.extentref_records.front().value, 0, (1ull << 60) | blocks);
        spec.authoritative_seeded_main_blocks.clear();
        for (std::uint64_t block = 0; block < blocks; ++block) {
            Bytes bytes(kBlockSize);
            for (std::size_t i = 0; i < bytes.size(); ++i) bytes[i] = std::byte((i * 13 + block * 47) % 251);
            spec.authoritative_seeded_main_blocks.push_back({kShared + block, std::move(bytes)});
        }
    }
    return spec;
}
std::filesystem::path Image() { return std::filesystem::absolute("replay.apfs"); }
std::filesystem::path Wal() { return std::filesystem::absolute("original.wal"); }
Bytes ReadFile(const std::filesystem::path& path) {
    std::ifstream in(path, std::ios::binary | std::ios::ate);
    Check(!!in && in.tellg() >= 0 && in.tellg() < 4 * 1024 * 1024, "bounded generated file read");
    Bytes bytes(static_cast<std::size_t>(in.tellg())); in.seekg(0);
    in.read(reinterpret_cast<char*>(bytes.data()), bytes.size()); Check(in.good(), "read generated bytes"); return bytes;
}
Store::VolumeContext Context() {
    Store::VolumeContext context; context.device_path = Image().wstring(); context.volume_object_id = 101;
    context.allow_legacy_scaffold_for_fixtures = false; return context;
}
std::string Identity(const Fixture& f) { return "apfs-vol:" + f.checkpoint.container.superblock.uuid_hex + ":101"; }
void OpenJournal(Tx& tx, const std::string& identity) {
    const std::wstring wide(identity.begin(), identity.end()); std::string error;
    Check(tx.OpenStartupJournal(Wal().wstring(), wide, error), "open original journal: " + error);
    if (!std::filesystem::exists(Wal())) Check(tx.MaterializeAbsentStartupJournal(error), error);
    Check(tx.EnrollCanonicalJournalIdentity(wide), "original journal identity");
}
PayloadSpool::Options SpoolOptions(const std::string& identity) {
    PayloadSpool::Options options; options.root = std::filesystem::absolute("original-spool");
    options.volume_identity = identity; return options;
}
void Produce(bool pending) {
    Fixture fixture(ReplaySpec()); auto expected = Payload(fixture, 17);
    NativeApfsVolumeProjection projection; std::string projection_error;
    Check(NativeApfsReader::TryProjectOrdinaryFileSystemRecords(ReadTree(fixture), fixture.checkpoint.container.superblock,
        fixture.checkpoint.volumes.front().superblock, std::make_shared<ApfsReadBudget>(65536, 256ull << 20, 262144, 256ull << 20),
        projection, projection_error), "strict replay preimage fixture: " + projection_error);
    std::copy(Patch.begin(), Patch.end(), expected.begin() + Offset);
    Check(!std::filesystem::exists(Image()) && !std::filesystem::exists(Wal()), "fresh private recovery fixture");
    { std::ofstream out(Image(), std::ios::binary); out.write(reinterpret_cast<const char*>(fixture.image.data()), fixture.image.size()); Check(out.good(), "save generated image"); }
    std::string error; auto device = BlockDevice::OpenExclusiveManagementImage(Image().wstring(), 0, error); Check(!!device, error);
    Store store(Context(), device); Check(store.PrepareNativeWritePath(), "producer writer");
    Tx tx(L"Strict"); OpenJournal(tx, Identity(fixture)); PayloadSpool spool(SpoolOptions(Identity(fixture)));
    Store::MutationRequest request; request.path = L"\\clone0"; request.offset = Offset; request.length = Patch.size();
    Store::PayloadIdentity identity;
    Check(store.StageMutation(request, &identity) == Store::MutationStatus::Applied, "stage producer write");
    Tx::MutationIntent intent; intent.kind = Tx::MutationKind::Write; intent.path = request.path;
    intent.object_id = identity.object_id; intent.generation = identity.generation;
    intent.offset = Offset; intent.length = Patch.size(); intent.wal_sequence = tx.NextMutationSequence();
    PayloadSpool::AppendResult appended;
    Check(spool.Append({Identity(fixture), identity.object_id, identity.generation, Offset, intent.wal_sequence, Patch}, &appended) &&
        spool.FlushPayloadBytes() && spool.FlushDirtyState(), "immutable accepted spool");
    intent.payload_spool_offset = appended.spool_offset; intent.payload_length = appended.payload_length;
    intent.payload_checksum = appended.payload_sha256; intent.inline_payload = Patch;
    const auto xid = store.CheckpointXid().value();
    Check(tx.Begin() && tx.RecordMutation(intent) && tx.Accept(xid), "original accepted WAL");
    Check(tx.FlushAcceptedEvidenceDurability(tx.Watermarks().accepted_sequence), "accepted evidence barrier");
    std::uint64_t supplied = 0;
    store.SetFilePayloadRangeProvider([&](const auto&, auto actual, auto offset, std::span<std::byte> bytes) {
        if (actual.object_id != identity.object_id || actual.generation != identity.generation || offset + bytes.size() > expected.size()) return false;
        supplied += bytes.size(); std::copy_n(expected.begin() + offset, bytes.size(), bytes.begin()); return true;
    });
    const auto cut = pending ? "before-apple-publish" : "after-apple-publish";
    store.SetCommitStageHook([&](auto stage) { return stage != cut; });
    Check(store.CommitCanonicalTransaction({xid}) != Store::CommitStatus::Committed && tx.HasUnappliedAcceptedWork(),
        "publication interruption preserves original accepted debt");
    std::cout << "PRODUCE pending=" << pending << " supplied=" << supplied << " accepted=" << tx.Watermarks().accepted_sequence << '\n';
}
void Prove(bool corrupt) {
    Fixture fixture(ReplaySpec()); const auto identity = Identity(fixture);
    std::string error;
    if (corrupt) {
        fixture.image = ReadFile(Image()); fixture.Reload();
        std::uint64_t byte = 0;
        for (const auto& record : ReadTree(fixture)) if (Type(record) == 8 && Id(record) == 17) {
            AppleFileExtentRecord extent; Check(DecodeAppleFileExtentRecord(record, kBlockSize, extent, error), error);
            if (Offset >= extent.logical_address && Offset - extent.logical_address < extent.length_bytes)
                byte = extent.physical_block * kBlockSize + Offset - extent.logical_address;
        }
        Check(byte != 0, "locate generated postimage corruption");
        std::fstream image(Image(), std::ios::binary | std::ios::in | std::ios::out);
        const char altered = 0x11; image.seekp(byte); image.write(&altered, 1); Check(image.good(), "corrupt only private generated payload");
    }
    auto device = BlockDevice::OpenExclusiveManagementImage(Image().wstring(), 0, error); Check(!!device, error);
    Store store(Context(), device); Check(store.PrepareNativeWritePath(), "cold retained proof source");
    Tx tx(L"Strict"); OpenJournal(tx, identity); PayloadSpool spool(SpoolOptions(identity));
    const auto before = ReadFile(Wal()); const auto marks = tx.Watermarks();
    Check(tx.FlushAcceptedEvidenceDurability(marks.accepted_sequence), "cold accepted evidence barrier");
    std::vector<std::uint64_t> applied;
    const bool result = store.ProveRetainedAcceptedPrefix(tx, spool, Wal(), identity, applied, error);
    Check(result != corrupt && (corrupt ? applied.empty() : applied == std::vector<std::uint64_t>{marks.accepted_sequence}),
        "exact retained layout proof: " + error);
    Check(ReadFile(Wal()) == before && tx.Watermarks().apfs_durable_sequence == marks.apfs_durable_sequence &&
        tx.Watermarks().cleanup_sequence == marks.cleanup_sequence, "proof changes no original journal or watermark");
    std::cout << "PROVE corrupt=" << corrupt << " matched=" << result << " error=" << error << '\n';
}
void ReplayPending(bool coordinator, bool tight = false) {
    const auto offset = tight ? kBlockSize : Offset;
    const Bytes patch = tight ? Bytes(kBlockSize, std::byte{0x99}) : Patch;
    Fixture fixture(ReplaySpec(tight)); auto expected = Payload(fixture, 17); std::copy(patch.begin(), patch.end(), expected.begin() + offset);
    Tx tx(L"Strict"); OpenJournal(tx, Identity(fixture)); PayloadSpool spool(SpoolOptions(Identity(fixture)));
    std::vector<Tx::AcceptedTransaction> batches; std::string error;
    Check(tx.LoadAcceptedTransactionsSinceCleanup(batches, &error) && batches.size() == 1 && batches.front().mutations.size() == 1,
        "exact original pending batch");
    const auto& batch = batches.front(); const auto& row = batch.mutations.front();
    Bytes persisted;
    Check(spool.ReadPersistedRange({Identity(fixture), row.object_id, row.parent_object_id, row.logical_offset,
        row.payload_length, row.payload_offset, row.payload_spool_id, row.payload_sha256}, persisted) && persisted == patch, "original persisted payload authority");
    Store::MutationRequest request; request.path = L"\\clone0"; request.object_id = row.object_id;
    request.generation = row.parent_object_id; request.offset = row.logical_offset; request.length = row.logical_length;
    std::uint64_t supplied = 0;
    const auto provider = [&](const auto&, auto actual, auto at, std::span<std::byte> bytes) {
        if (actual.object_id != row.object_id || actual.generation != row.parent_object_id || at + bytes.size() > expected.size()) return false;
        supplied += bytes.size(); std::copy_n(expected.begin() + at, bytes.size(), bytes.begin()); return true;
    };
    const auto before = ReadFile(Wal());
    if (coordinator) {
        auto owner = ContainerMountCoordinator::Open(Image().string(), 0, error, CatalogLoadPolicy::StrictApple, true, true, true);
        Check(!!owner, "generated coordinator source: " + error);
        Check(owner->InitializeRequiredCheckpointCensus({{101, {batch.preimage_checkpoint_xid}, true}}, error), error);
        ContainerVolumeSession session; session.volume_object_id = 101; session.container_uuid_hex = owner->ContainerUuidHex();
        session.requested_write = session.use_canonical_transaction = true;
        session.metadata_context.allow_native_snapshot_runtime = true;
        Check(owner->MountVolume(session, error), "generated session: " + error);
        owner->FindSessionStore(101)->SetFilePayloadRangeProvider(provider);
        const auto result = owner->Commit(101, {request}, {}, {}, {}, true, batch.preimage_checkpoint_xid);
        Check(result.committed, "accepted coordinator replay: " + result.error);
    } else {
        auto device = BlockDevice::OpenExclusiveManagementImage(Image().wstring(), 0, error); Check(!!device, error);
        Store store(Context(), device); Check(store.PrepareNativeWritePath(), "direct startup source");
        Check(store.StageMutation(request) == Store::MutationStatus::Applied, "restage exact original pending incarnation");
        store.SetFilePayloadRangeProvider(provider);
        Check(store.CheckPendingAppleCapacity({batch.preimage_checkpoint_xid}) == Store::CommitStatus::NothingToCommit,
            "pending logical replay admission");
        Check(store.CommitCanonicalTransaction({batch.preimage_checkpoint_xid}) == Store::CommitStatus::Committed, "pending logical replay publication");
    }
    Check(supplied == kBlockSize && ReadFile(Wal()) == before, "unpublished logical replay uses admitted compact policy and preserves original WAL");
    fixture.image = ReadFile(Image()); fixture.Reload();
    Check(Payload(fixture, 17) == expected, "cold accepted replay bytes"); CheckGraph(fixture);
    std::cout << "REPLAY coordinator=" << coordinator << " supplied=" << supplied << '\n';
}
void LiveCoordinator(bool worker, bool expect_refused) {
    constexpr auto offset = kBlockSize;
    const Bytes patch(kBlockSize, std::byte{0x99});
    Fixture fixture(ReplaySpec(true)); const auto original = Payload(fixture, 17);
    auto expected = original; std::copy(patch.begin(), patch.end(), expected.begin() + offset);
    Check(!std::filesystem::exists(Image()) && !std::filesystem::exists(Wal()), "fresh tight-space live fixture");
    { std::ofstream out(Image(), std::ios::binary); out.write(reinterpret_cast<const char*>(fixture.image.data()), fixture.image.size()); Check(out.good(), "save tight-space source"); }
    std::string error;
    auto owner = ContainerMountCoordinator::Open(Image().string(), 0, error, CatalogLoadPolicy::StrictApple, true, true, true);
    Check(!!owner && owner->InitializeRequiredCheckpointCensus({{101, {}, false}}, error), "live complete census: " + error);
    ContainerVolumeSession session; session.volume_object_id = 101; session.container_uuid_hex = owner->ContainerUuidHex();
    session.requested_write = session.use_canonical_transaction = true;
    session.metadata_context.allow_native_snapshot_runtime = true;
    session.metadata_context.allow_legacy_scaffold_for_fixtures = false;
    Check(owner->MountVolume(session, error), "live strict session: " + error);
    auto* store = owner->FindSessionStore(101); const auto xid = owner->CheckpointXid();
    Tx tx(L"Strict"); OpenJournal(tx, Identity(fixture)); PayloadSpool spool(SpoolOptions(Identity(fixture)));
    Store::MutationRequest request; request.path = L"\\clone0"; request.offset = offset; request.length = patch.size();
    request.object_id = 17; request.generation = xid + 1; request.deferred_payload = patch;
    unsigned acceptances = 0; std::uint64_t supplied = 0;
    store->SetFilePayloadRangeProvider([&](const auto&, auto actual, auto at, std::span<std::byte> bytes) {
        if (actual.object_id != request.object_id || actual.generation != request.generation || at + bytes.size() > expected.size()) return false;
        supplied += bytes.size(); std::copy_n(expected.begin() + at, bytes.size(), bytes.begin()); return true;
    });
    const auto accept = [&](const auto& requests, const auto& identities, auto preimage, auto& pins, auto& why) {
        Check(requests.size() == 1 && identities.size() == 1 && preimage == xid && supplied == 0, "capacity precedes acceptance without payload I/O");
        Check(identities[0].object_id == request.object_id && identities[0].generation == request.generation, "modern live mutation already has incarnation");
        Tx::MutationIntent intent; intent.kind = Tx::MutationKind::Write; intent.path = request.path;
        intent.object_id = identities[0].object_id; intent.generation = identities[0].generation;
        intent.offset = offset; intent.length = patch.size(); intent.wal_sequence = tx.NextMutationSequence();
        PayloadSpool::AppendResult appended;
        Check(spool.Append({Identity(fixture), intent.object_id, intent.generation, offset, intent.wal_sequence, patch}, &appended) &&
            spool.FlushPayloadBytes() && spool.FlushDirtyState(), "live durable accepted spool");
        intent.payload_spool_offset = appended.spool_offset; intent.payload_length = appended.payload_length;
        intent.payload_checksum = appended.payload_sha256; intent.inline_payload = patch;
        Check(tx.Begin() && tx.RecordMutation(intent) && tx.Accept(preimage) &&
            tx.FlushAcceptedEvidenceDurability(tx.Watermarks().accepted_sequence), "live durable accepted WAL");
        ++acceptances; return tx.LoadRequiredCheckpointXidsSinceCleanup(pins, &why);
    };
    const auto result = owner->Commit(101, {request}, accept, {}, {}, false, std::nullopt, {}, {}, true, true);
    Bytes held_image;
    Check(owner->Device().ReadForVerification(0, fixture.image.size(), held_image), "read through held exclusive fixture owner");
    if (expect_refused) {
        Check(!result.accepted_without_publication && !result.committed && acceptances == 0 &&
            result.commit_stage == "before-wal-capacity-admission", "old engine cannot admit tight-space whole-file COW: " + result.error);
        Check(held_image == fixture.image && !tx.HasUnappliedAcceptedWork(), "legacy capacity refusal writes no payload or acceptance");
        std::cout << "LEGACY_CAPACITY refused=" << result.error << '\n'; return;
    }
    Check(result.accepted_without_publication && !result.committed && acceptances == 1 && supplied == 0 &&
        tx.HasUnappliedAcceptedWork() && held_image == fixture.image, "compact acceptance survives exact prepublication crash boundary: " + result.error);
    std::cout << "LIVE accepted=1 boundIncarnation=1 freeBlocks=" << fixture.checkpoint.spaceman.devices[0].free_count << " legacyPayloadBlocks=352\n";
    if (worker) {
        const auto wal = ReadFile(Wal());
        const auto published = owner->Commit(101, {});
        Check(published.committed && supplied == kBlockSize && ReadFile(Wal()) == wal, "live accepted worker retains compact publication policy: " + published.error);
        owner.reset(); fixture.image = ReadFile(Image()); fixture.Reload();
        Check(Payload(fixture, 17) == expected && Payload(fixture, 17, xid) == original, "cold worker payload and retained owner bytes");
        CheckGraph(fixture);
        std::cout << "LIVE_WORKER supplied=" << supplied << '\n';
    }
}
